from __future__ import annotations

from collections.abc import Callable
from typing import Any, ClassVar

from glances.plugins.llm_reporter.llm_reporter import Reporter
from glances.plugins.plugin.base import GlancesPluginBase

AlertReader = Callable[[], dict[tuple[str, str | None, str], str]]
_DEFAULT_LLM_REFRESH_TIME = 300


class PluginModel(GlancesPluginBase):
    plugin_name: ClassVar[str] = "llm_reporter"
    IS_COLLECTION: ClassVar[bool] = False
    EMITS_ALERTS = False
    EXPORTABLE = True  # TODO True or False?
    DISABLED_BY_DEFAULT = True
    # DEFAULT_REFRESH_TIME = _DEFAULT_LLM_REFRESH_TIME #TODO Uncomment this and delete line below
    DEFAULT_REFRESH_TIME = _DEFAULT_LLM_REFRESH_TIME
    fields_description: ClassVar[dict[str, dict[str, Any]]] = {
        "report": {
            "description": "The text report generated by the LLM based on current system metrics",
            "unit": "string",
        },
        "model": {"description": "Model used to generate the report", "unit": "string"},
        "status": {
            "description": "Status of the system as determined by the reporter. ok | degraded | critical",
            "unit": "string",
        },
    }

    def __init__(self, store: Any, config: Any) -> None:
        super().__init__(store, config)
        self.alert_source: AlertReader | None = None
        self.llm_reporter = Reporter(config)

    def set_alert_source(self, reader: AlertReader):
        self.alert_source = reader

    def _recognises_threshold_key(self, remainder: str) -> bool:
        # LLM reporter is not like other plugins that generate alerts when certain usage threshholds are exceeded.
        return True

    async def _grab_stats(self) -> dict:
        report = self.llm_reporter("hello there")  # TODO Offload to ayncio thread?
        return {
            "status": "ok",
            "report": report,
            "model": "gpt-5.6-Sol-Think-deeper",
        }
